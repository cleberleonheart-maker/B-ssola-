export const LANGS: { key: Lang; label: string }[] = [
  { key: 'pt', label: 'Português (Brasil)' },
  { key: 'en', label: 'English' },
  { key: 'es', label: 'Español' },
];

type Params = Record<string, string | number>;

const fill = (template: string, params?: Params): string => {
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (m, k: string) =>
    params[k] != null ? String(params[k]) : m,
  );
};

export type Translator = (key: string, params?: Params) => string;

export const createTranslator = (lang: Lang): Translator => {
  const table: Record<string, string> = STRINGS[lang] ?? STRINGS.pt;
  const ptTable: Record<string, string> = STRINGS.pt;
  return (key, params) => {
    const template = table[key] ?? ptTable[key] ?? key;
    return fill(template, params);
  };
};

